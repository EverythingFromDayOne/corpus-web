#!/usr/bin/env node
/**
 * build-article-bodies.mjs
 *
 * Session 169 (D45 close). The article-render codepath calls
 * `readArticleMarkdown(article)` which does
 * `readFileSync(articleFilePath(article), 'utf8')` at request time
 * (inside a `'use cache'` block). Today that fs read is dormant: the
 * function is only called from the prerender pass, which runs in the
 * build container where the filesystem is readable. The D43 ENOENT
 * fired because that build container / Lambda boundary was crossed at
 * request time when Quiz grading was wired into a Server Action.
 *
 * `readArticleMarkdown` has not been wired to a Server Action yet —
 * but the moment someone writes `gradeReadingTimeEstimate()` or any
 * other action that needs the markdown body, the same ENOENT fires
 * the way D43 did. The D43 fix landed in `fix/d43-answer-keys`
 * (PR landed 2026-09-04, deployed verified on `nxhhuy.tech` via
 * PR #161 promotion, tag v0.1.0). This script applies the same
 * emit-then-static-import pattern to the article bodies: at prebuild
 * time, walk every adapting article from `catalog.json`, strip the
 * YAML frontmatter, and emit a single static TS module at
 * `apps/web/lib/data/article-bodies.ts`. Turbopack bundles that
 * module into the Lambda as part of the app graph, so the runtime
 * read becomes a plain static import — no fs read at request time,
 * no ENOENT on the serverless Lambda.
 *
 * Output module size: 196 articles × ~20 KB average stripped body =
 * ~4 MB. The Vercel Lambda bundle limit is 250 MB uncompressed / 50 MB
 * compressed — the 4 MB module fits comfortably. The git-tracked size
 * would balloon the repo on every content submodule bump, so the file
 * is **gitignored** (same treatment as `catalog.json`) and gates fail
 * loudly if it is missing. `pnpm build:catalog` is still required
 * first because this script reads the resulting `catalog.json`.
 *
 * The script does NOT replace `readFileSync` patterns elsewhere. There
 * are other fs reads in `catalog.ts` (`loadCatalogView`) that are also
 * build-time-only today (called from `'use cache'` wrappers and from
 * `generateStaticParams`). D43 only fixed the action-path fs reads
 * because those were the ones that actually crossed the
 * build-container / Lambda boundary at request time. D45 fixes the
 * one read in the article-render codepath that has the same latent
 * risk. Future Server-Action wiring that crosses the boundary needs
 * its own row.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const CATALOG_PATH = join(ROOT, 'catalog.json');
const OUT_PATH = join(ROOT, 'apps/web/lib/data/article-bodies.ts');

function frontmatterStrip(raw) {
  // Matches `apps/web/lib/article-source.ts:9`. Keep these in lock-step.
  return raw.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '');
}

function build() {
  if (!existsSync(CATALOG_PATH)) {
    console.error(
      'build-article-bodies: FAIL — catalog.json does not exist. ' +
        'Run `pnpm build:catalog` first.',
    );
    process.exit(1);
  }

  const catalog = JSON.parse(readFileSync(CATALOG_PATH, 'utf8'));
  if (!Array.isArray(catalog.articles) || catalog.articles.length === 0) {
    console.error(
      'build-article-bodies: FAIL — catalog.json has no articles. ' +
        'Refusing to emit an empty module.',
    );
    process.exit(1);
  }

  mkdirSync(join(ROOT, 'apps/web/lib/data'), { recursive: true });

  const articleBodies = {};
  let totalBytes = 0;
  let missing = 0;
  for (const article of catalog.articles) {
    const path = join(ROOT, 'content', article.repo, article.sourcePath);
    if (!existsSync(path)) {
      // Defensive — catalog.json should only contain articles that
      // adapted from real files, but if a submodule is out of sync,
      // skip the missing entry and keep going rather than failing
      // the entire build. The verify gates catch the root cause.
      missing += 1;
      continue;
    }
    const raw = readFileSync(path, 'utf8');
    const stripped = frontmatterStrip(raw);
    articleBodies[article.uid] = stripped;
    totalBytes += stripped.length;
  }

  if (Object.keys(articleBodies).length === 0) {
    console.error(
      'build-article-bodies: FAIL — zero article bodies emitted. ' +
        'Check that the four submodules are initialised ' +
        '(`pnpm sync:content`).',
    );
    process.exit(1);
  }

  const articleUids = Object.keys(articleBodies).sort();

  const header =
    '// AUTO-GENERATED by scripts/build-article-bodies.mjs — DO NOT EDIT.\n' +
    '// Source: every adapting article in catalog.json, frontmatter stripped.\n' +
    '// Consumed by apps/web/lib/article-source.ts (article-render codepath).\n' +
    '// The static import means Turbopack bundles this module into the\n' +
    "// Lambda — no fs read at request time, so Vercel's serverless runtime\n" +
    "// can resolve it (the `content/<repo>/` submodule gitlinks are not\n" +
    "// part of the deployment bundle). Closes D45 — same shape as D43's\n" +
    '// answer-keys.ts (deployed verified via PR #161 / v0.1.0).\n\n';

  const dataJson = JSON.stringify(
    { articleUids, articleBodies },
    (_key, value) => value,
    2,
  );

  const typeBlock =
    'export type ArticleBodiesModule = {\n' +
    '  readonly articleUids: readonly string[];\n' +
    '  readonly articleBodies: Readonly<Record<string, string>>;\n' +
    '};\n';

  // The cast widens the narrow literal-keyed, deeply-readonly shape that
  // JSON.stringify + `as const` produce into the loose
  // Record<string, string> shape that consumers need after the Set
  // membership gate. Runtime values are identical — only the static
  // type changes.
  const body =
    'export const articleBodies = ' +
    dataJson +
    ' as const;\n\n' +
    typeBlock +
    '// The cast below widens the narrow literal-keyed, deeply-readonly\n' +
    "// shape that JSON.stringify + `as const` produce into the loose\n" +
    '// Record<string, string> shape that consumers need. The runtime\n' +
    '// values are identical — only the static type changes.\n' +
    'export const articleBodiesByUid = articleBodies.articleBodies as unknown as Readonly<Record<string, string>>;\n';

  writeFileSync(OUT_PATH, header + body, 'utf8');

  console.log(
    'build-article-bodies: wrote ' +
      OUT_PATH.replace(ROOT + '/', '') +
      ' — ' +
      articleUids.length +
      ' article(s), ' +
      Math.round(totalBytes / 1024) +
      ' KB total' +
      (missing > 0 ? ', ' + missing + ' missing (skipped)' : '') +
      '.',
  );
}

try {
  build();
} catch (err) {
  console.error('build-article-bodies: FAIL — ' + err.message);
  process.exit(1);
}
