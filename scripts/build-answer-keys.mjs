#!/usr/bin/env node
/**
 * build-answer-keys.mjs
 *
 * Session 165 (D43 close). The Quiz + DragDrop server actions
 * (`gradeQuizAnswer` / `gradeDragDrop`) need the answer keys for each
 * article at request time. PR #146 was supposed to fix this but
 * verified against `pnpm start`, which reads `catalog.json` and the
 * curation YAMLs from disk via `readFileSync` — a code path that fails
 * on Vercel's serverless runtime because the Lambda bundle ships from
 * `next build`'s output, and neither `catalog.json` (gitignored
 * build artifact at repo root) nor `curation/overrides/*.yaml`
 * (hand-authored files in repo root, not under `apps/web/`) are
 * reachable from the deployed bundle.
 *
 * Fix: this script reads every curation override YAML at build time,
 * extracts the per-article quiz + dragdrop answer keys, and emits a
 * single static TS module at `apps/web/lib/data/answer-keys.ts`.
 * Turbopack bundles that module into the Lambda as part of the app
 * graph, so the action handler gets answer keys via a plain static
 * import — no `readFileSync`, no runtime fs dependency, no ENOENT.
 *
 * The script does NOT replace `catalog.json`. `verify-catalog`,
 * `verify-prerender`, and Pagefind's indexer still read the JSON file
 * from disk (see D22 SEO baseline + D21 Pagefind wiring). Two
 * artifacts, two consumers, intentionally separate — per user
 * directive "keep writing catalog.json as well" (session 165).
 *
 * Output module size: 6 articles × ~14 quiz questions + 6 dragdrop
 * widgets = ~30 KB pretty-printed. Compare to the 978 KB
 * `catalog.json`. The action path now pulls only what it needs.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import YAML from 'yaml';
import {
  OverrideFile,
} from '../packages/content-schema/src/index.ts';

// `import.meta.dirname` here is `scripts/` (this file's location). One `..`
// segment walks up to the repo root. The peer `scripts/lib/corpus-fs.mjs`
// uses two `..` because it lives one level deeper.
const ROOT = resolve(import.meta.dirname, '..');
const OVERRIDES_DIR = join(ROOT, 'curation', 'overrides');
const OUT_PATH = join(
  ROOT,
  'apps/web/lib/data/answer-keys.ts',
);

function jsonReplacer(_key, value) {
  return value;
}

/**
 * One override YAML's quiz + dragdrop injection props, projected into
 * the answer-key shape the server actions consume. Validation against
 * the existing schema modules happens upstream — this script trusts
 * that the override file's Quiz props match `QuizQuestion` and the
 * DragDrop props match `DragDropSidecar` (the schemas live in
 * `packages/content-schema/src/sidecars.ts` + `dragdrop-sidecar.ts`).
 */
function projectAnswerKeys(file) {
  const out = { quiz: {}, dragdrop: {} };
  for (const inject of file.inject) {
    if (inject.component === 'Quiz') {
      const props = inject.props;
      const questions = Array.isArray(props.quiz)
        ? props.quiz.flatMap((block) => block.questions)
        : props.questions
          ?? (props.quiz ? props.quiz.questions : []);
      for (const question of questions) {
        const correct = question.options.find((opt) => opt.correct);
        if (!correct) continue;
        out.quiz[question.id] = {
          correctLabel: correct.label,
          explanation: question.explanation,
          validLabels: question.options.map((opt) => opt.label),
        };
      }
    }
    if (inject.component === 'DragDrop') {
      const props = inject.props;
      out.dragdrop[props.id] = {
        sidecarId: props.id,
        mode: props.mode ?? 'exact',
        slots: props.slots,
        chips: props.chips,
        explanation: props.explanation ?? '',
      };
    }
  }
  return out;
}

function build() {
  // Make sure the output directory exists — `apps/web/lib/data/` is
  // freshly created by this script on first run.
  mkdirSync(join(ROOT, 'apps/web/lib/data'), { recursive: true });

  if (!existsSync(OVERRIDES_DIR)) {
    writeFileSync(
      OUT_PATH,
      "// AUTO-GENERATED by scripts/build-answer-keys.mjs — DO NOT EDIT.\n" +
      "// Empty: no curation/overrides/ directory exists.\n" +
      "export const answerKeys = { articleUids: [], byArticle: {} } as const;\n",
      'utf8',
    );
    console.log('build-answer-keys: no overrides directory — emitted empty module.');
    return;
  }

  const files = readdirSync(OVERRIDES_DIR).filter(
    (file) => file.endsWith('.yaml') || file.endsWith('.yml'),
  );
  if (files.length === 0) {
    writeFileSync(
      OUT_PATH,
      "// AUTO-GENERATED by scripts/build-answer-keys.mjs — DO NOT EDIT.\n" +
      "// Empty: no override YAMLs found.\n" +
      "export const answerKeys = { articleUids: [], byArticle: {} } as const;\n",
      'utf8',
    );
    console.log('build-answer-keys: no override YAMLs — emitted empty module.');
    return;
  }

  const byArticle = {};
  let quizCount = 0;
  let dragdropCount = 0;
  for (const file of files) {
    const path = join(OVERRIDES_DIR, file);
    const raw = YAML.parse(readFileSync(path, 'utf8'));
    const parsed = OverrideFile.safeParse(raw);
    if (!parsed.success) {
      const issues = parsed.error.issues
        .map((issue) => `${issue.path.join('.') || '(root)'} ${issue.message}`)
        .join('; ');
      throw new Error(`curation/overrides/${file}: ${issues}`);
    }
    const projected = projectAnswerKeys(parsed.data);
    if (Object.keys(projected.quiz).length === 0 && Object.keys(projected.dragdrop).length === 0) {
      continue;
    }
    byArticle[parsed.data.article] = projected;
    quizCount += Object.keys(projected.quiz).length;
    dragdropCount += Object.keys(projected.dragdrop).length;
  }

  const articleUids = Object.keys(byArticle).sort();

  const header =
    '// AUTO-GENERATED by scripts/build-answer-keys.mjs — DO NOT EDIT.\n' +
    '// Source: every YAML in curation/overrides/, parsed at build time.\n' +
    '// Consumed by apps/web/lib/{quiz,dragdrop}-actions.ts (Server Actions).\n' +
    '// The static import means Turbopack bundles this module into the\n' +
    '// Lambda — no fs read at request time, so Vercel\'s serverless runtime\n' +
    '// can resolve it (catalog.json + curation YAMLs are not in the bundle).\n' +
    '// Schema: see packages/content-schema/src/{sidecars,dragdrop-sidecar}.ts.\n\n';

  const dataJson = JSON.stringify({ articleUids, byArticle }, jsonReplacer, 2);

  const typeBlock =
    'export type QuizAnswerKey = {\n' +
    '  correctLabel: string;\n' +
    '  explanation: string;\n' +
    '  validLabels: string[];\n' +
    '};\n\n' +
    'export type DragDropAnswerKey = {\n' +
    '  sidecarId: string;\n' +
    "  mode: 'exact' | 'ordered';\n" +
    '  slots: ReadonlyArray<{ id: string; label?: string; accepts: string[] }>;\n' +
    '  chips: ReadonlyArray<{ id: string; text: string; correctSlots: string[] }>;\n' +
    '  explanation: string;\n' +
    '};\n\n' +
    'export type ArticleAnswerEntry = {\n' +
    '  readonly quiz: Readonly<Record<string, QuizAnswerKey>>;\n' +
    '  readonly dragdrop: Readonly<Record<string, DragDropAnswerKey>>;\n' +
    '};\n\n' +
    'export type AnswerKeysModule = {\n' +
    '  readonly articleUids: readonly string[];\n' +
    '  readonly byArticle: Readonly<Record<string, ArticleAnswerEntry>>;\n' +
    '};\n';

  // `byArticle` from the JSON.stringify above has narrow string-literal
  // keys (each article uid). Consumer code needs to index by an arbitrary
  // article string, so we re-expose a loose-typed projection. The narrow
  // shape stays on `answerKeys` for build-time iteration; the loose shape
  // on `answerKeysByArticle` is what the server actions use after the
  // Set membership gate.
  const body =
    'export const answerKeys = ' + dataJson + ' as const;\n\n' +
    typeBlock +
    '// The cast below widens the narrow literal-keyed, deeply-readonly\n' +
    '// shape that JSON.stringify + `as const` produce into the loose\n' +
    '// Record<string, …> shape that the server actions need. The\n' +
    '// runtime values are identical — only the static type changes.\n' +
    'export const answerKeysByArticle = answerKeys.byArticle as unknown as Readonly<Record<string, ArticleAnswerEntry>>;\n';

  writeFileSync(OUT_PATH, header + body, 'utf8');

  console.log(
    `build-answer-keys: wrote ${OUT_PATH.replace(ROOT + '/', '')} — ` +
    `${articleUids.length} article(s), ${quizCount} quiz answer key(s), ` +
    `${dragdropCount} drag-drop answer key(s).`,
  );
}

try {
  build();
} catch (err) {
  console.error(`build-answer-keys: FAIL — ${err.message}`);
  process.exit(1);
}
