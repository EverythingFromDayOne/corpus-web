#!/usr/bin/env node
/**
 * audit-frontmatter.mjs
 *
 * Session 2 task 2. Walks every `.md` file under each of the four mounted
 * submodules, parses frontmatter with gray-matter, and runs it through the
 * adapters in `packages/content-schema/src/adapters/index.ts`.
 *
 * Also reports every `.md` file on disk that the adapter's `conceptsRoot` /
 * `recipesRoot` rules do NOT select, so a directory-shape mismatch (the
 * headline session-1 finding for `react`/`nestjs`) is visible even after it is
 * fixed, rather than only before.
 *
 * Usage:
 *   pnpm audit:frontmatter                  write docs/audit/frontmatter-<date>.md
 *   pnpm audit:frontmatter -- --out <path>  write to an explicit path
 */
import matter from 'gray-matter';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import {
  CONTENT_DIR,
  listAllMarkdownFiles,
  listTopLevelDirs,
  ROOT,
  selectArticleFiles,
  sha256,
} from './lib/corpus-fs.mjs';
import { ADAPTERS, AdapterError, isIndexFile, RepoId } from '../packages/content-schema/src/index.ts';

const MAX_EXAMPLES = 6;
const mountedRepos = RepoId.options;

const sections = [];
sections.push('# Frontmatter audit\n');
sections.push(
  'Generated by `scripts/audit-frontmatter.mjs` against the adapters in ' +
    '`packages/content-schema/src/adapters/index.ts`, run for real against the ' +
    'four mounted submodules. Re-run after any adapter change — this file is ' +
    'evidence, not a one-time snapshot.\n',
);

for (const repo of mountedRepos) {
  const repoDir = join(CONTENT_DIR, repo);
  const adapter = ADAPTERS[repo];

  sections.push(`\n---\n\n## \`${repo}\`\n`);

  if (!existsSync(repoDir)) {
    sections.push(`**Not on disk at \`content/${repo}\`.** Run \`pnpm sync:content\` first. Skipped.\n`);
    continue;
  }

  const allFiles = listAllMarkdownFiles(repoDir);
  const { concepts, recipes, all: selected } = selectArticleFiles(repoDir, adapter, isIndexFile);
  const unselected = allFiles.filter((f) => !selected.includes(f));

  sections.push(
    `**Adapter roots:** conceptsRoot=\`${adapter.conceptsRoot ?? '(repo root)'}\`, ` +
      `recipesRoot=\`${adapter.recipesRoot}\`` +
      (adapter.excludeDirs.length ? `, excludeDirs=[${adapter.excludeDirs.map((d) => `\`${d}\``).join(', ')}]` : ''),
  );
  sections.push(`- Files on disk (all \`.md\`/\`.mdx\`, recursive): **${allFiles.length}**`);
  sections.push(`- Selected as articles (concepts: ${concepts.length}, recipes: ${recipes.length}): **${selected.length}**`);
  sections.push(`- On disk but NOT selected (support files, indexes, other corpora tooling): **${unselected.length}**\n`);

  if (selected.length === 0 && allFiles.length > 0) {
    sections.push(
      `> **FINDING: zero files selected while ${allFiles.length} \`.md\` files exist.** ` +
        `The adapter's directory assumption is still wrong for this corpus.\n`,
    );
  }

  const topDirs = listTopLevelDirs(repoDir);
  sections.push('**On-disk top-level directories and their `.md` counts:**\n');
  sections.push('| Directory | `.md` files (recursive) | Selected |');
  sections.push('|---|---|---|');
  for (const dir of topDirs) {
    const count = allFiles.filter((f) => f === dir || f.startsWith(`${dir}/`)).length;
    const selectedCount = selected.filter((f) => f.startsWith(`${dir}/`)).length;
    sections.push(`| \`${dir}/\` | ${count} | ${selectedCount} |`);
  }
  const rootFiles = allFiles.filter((f) => !f.includes('/'));
  if (rootFiles.length > 0) {
    sections.push(`| *(repo root)* | ${rootFiles.length} — ${rootFiles.map((f) => `\`${f}\``).join(', ')} | 0 |`);
  }
  sections.push('');

  let parsedOk = 0;
  let parsedFail = 0;
  let adaptedOk = 0;
  let adaptedFail = 0;
  /** @type {Map<string, { count: number, examples: string[] }>} */
  const keyStats = new Map();
  /** @type {Map<string, { count: number, examples: string[] }>} */
  const statusValues = new Map();
  /** @type {Map<string, { count: number, examples: string[] }>} */
  const difficultyValues = new Map();
  /** @type {Map<string, { count: number, examples: string[] }>} */
  const baselineValues = new Map();
  /** @type {Map<string, { count: number, examples: string[] }>} */
  const failureReasons = new Map();
  /** @type {Array<{ path: string, raw: string, reason: string }>} */
  const unresolvedRelated = [];

  const baselineKey = adapterBaselineKey(repo);
  const recognisedKeys = adapterRecognisedKeys(repo);

  for (const relPath of selected) {
    const abs = join(repoDir, relPath);
    const raw = readFileSync(abs, 'utf8');

    let parsed;
    try {
      parsed = matter(raw);
      parsedOk += 1;
    } catch (err) {
      parsedFail += 1;
      record(failureReasons, `YAML parse error: ${err.message}`, relPath);
      continue;
    }

    const fm = parsed.data ?? {};
    for (const key of Object.keys(fm)) {
      record(keyStats, key, relPath);
    }
    if ('status' in fm) record(statusValues, stringifyValue(fm.status), relPath);
    if ('difficulty' in fm) record(difficultyValues, stringifyValue(fm.difficulty), relPath);
    if (baselineKey && baselineKey in fm) record(baselineValues, stringifyValue(fm[baselineKey]), relPath);

    if (Array.isArray(fm.related)) {
      for (const entry of fm.related) {
        if (typeof entry !== 'string' || !entry.trim()) {
          unresolvedRelated.push({ path: relPath, raw: String(entry), reason: 'empty or non-string entry' });
        }
      }
    }

    try {
      ADAPTERS[repo].toArticle({
        frontmatter: fm,
        sourcePath: relPath,
        body: parsed.content,
        contentHash: sha256(parsed.content),
        sections: [],
      });
      adaptedOk += 1;
    } catch (err) {
      adaptedFail += 1;
      const reason = err instanceof AdapterError ? err.message : `${err.name}: ${err.message}`;
      record(failureReasons, normaliseReason(reason), relPath);
    }
  }

  sections.push(`**Adapter run, over the ${selected.length} selected file(s):**\n`);
  sections.push(`- Parsed (frontmatter extracted): ${parsedOk} ok, ${parsedFail} failed`);
  sections.push(`- Adapted to \`Article\`: ${adaptedOk} ok, ${adaptedFail} failed\n`);

  sections.push('**Distinct frontmatter keys observed** (adapter-recognised keys marked):\n');
  sections.push('| Key | Count | Recognised by adapter? | Example |');
  sections.push('|---|---|---|---|');
  for (const [key, info] of [...keyStats.entries()].sort((a, b) => b[1].count - a[1].count)) {
    const recognised = recognisedKeys.has(key) ? 'yes' : '**no**';
    sections.push(`| \`${key}\` | ${info.count} | ${recognised} | \`${info.examples[0]}\` |`);
  }
  sections.push('');

  sections.push('**Distinct `status` values:**\n');
  sections.push(mapToList(statusValues) || '_(none observed)_\n');

  sections.push('**Distinct `difficulty` values:**\n');
  sections.push(mapToList(difficultyValues) || '_(none observed)_\n');

  sections.push(`**Distinct \`${baselineKey ?? 'baseline'}\` values:**\n`);
  sections.push(mapToList(baselineValues) || '_(none observed)_\n');

  sections.push('**Unresolved `related` entries** (malformed at parse time — full cross-reference resolution is the catalog builder, task 5):\n');
  if (unresolvedRelated.length === 0) {
    sections.push('_(none)_\n');
  } else {
    sections.push('| Source path | Raw value | Reason |');
    sections.push('|---|---|---|');
    for (const u of unresolvedRelated.slice(0, MAX_EXAMPLES)) {
      sections.push(`| \`${u.path}\` | \`${u.raw}\` | ${u.reason} |`);
    }
    sections.push('');
  }

  sections.push('**Adaptation failures, grouped by reason:**\n');
  if (failureReasons.size === 0) {
    sections.push('_(none)_\n');
  } else {
    for (const [reason, info] of [...failureReasons.entries()].sort((a, b) => b[1].count - a[1].count)) {
      sections.push(`- **${info.count}×** ${reason}`);
      sections.push(`  - examples: ${info.examples.map((e) => `\`${e}\``).join(', ')}`);
    }
    sections.push('');
  }
}

const report = sections.join('\n') + '\n';
const outIdx = process.argv.indexOf('--out');
const outPath =
  outIdx !== -1 && process.argv[outIdx + 1]
    ? join(ROOT, process.argv[outIdx + 1])
    : join(ROOT, 'docs', 'audit', `frontmatter-${todayStamp()}.md`);

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, report, 'utf8');
console.log(`audit-frontmatter: wrote ${relativeToRoot(outPath)}`);

// ---------------------------------------------------------------------------

/** @param {Map<string, { count: number, examples: string[] }>} map @param {string} key @param {string} example */
function record(map, key, example) {
  const entry = map.get(key) ?? { count: 0, examples: [] };
  entry.count += 1;
  if (entry.examples.length < MAX_EXAMPLES) entry.examples.push(example);
  map.set(key, entry);
}

/** @param {unknown} value */
function stringifyValue(value) {
  if (typeof value === 'string') return value;
  return JSON.stringify(value);
}

/** Collapse a per-file source path out of an AdapterError message so identical failure types group together. */
function normaliseReason(message) {
  return message.replace(/^\[[^\]]+\]\s*[^:]+:\s*/, '').trim();
}

/** @param {Map<string, { count: number, examples: string[] }>} map */
function mapToList(map) {
  if (map.size === 0) return '';
  const lines = ['| Value | Count | Example |', '|---|---|---|'];
  for (const [value, info] of [...map.entries()].sort((a, b) => b[1].count - a[1].count)) {
    lines.push(`| \`${value}\` | ${info.count} | \`${info.examples[0]}\` |`);
  }
  return lines.join('\n') + '\n';
}

/** @param {string} repo */
function adapterBaselineKey(repo) {
  const map = { nextjs: 'next_baseline', react: 'react_baseline', angular: 'angular_baseline', nestjs: 'nest_baseline' };
  return map[repo] ?? null;
}

/** Keys the corresponding adapter spec actually reads. Kept here, not imported, so the report reflects intent independent of implementation drift. */
function adapterRecognisedKeys(repo) {
  const common = new Set(['title', 'description', 'status', 'wave', 'difficulty', 'related']);
  const perRepo = {
    nextjs: ['article_id', 'recipe_id', 'concept_folder', 'next_baseline'],
    react: ['article_id', 'recipe_id', 'concept_folder', 'react_baseline', 'primary_concept'],
    angular: ['article_id', 'recipe_id', 'concept_folder', 'angular_baseline'],
    nestjs: ['article_id', 'recipe_id', 'concept_folder', 'nest_baseline'],
  };
  for (const key of perRepo[repo] ?? []) common.add(key);
  return common;
}

function todayStamp() {
  return new Date().toISOString().slice(0, 10);
}

/** @param {string} p */
function relativeToRoot(p) {
  return p.startsWith(ROOT) ? p.slice(ROOT.length + 1) : p;
}
